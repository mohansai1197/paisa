#!/usr/bin/env python3
"""Build the React frontend into one executable Spring Boot application."""
import argparse
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--frontend-already-built", action="store_true", help="Reuse a verified current frontend/dist build")
    parser.add_argument("--tests-already-passed", action="store_true", help="Reuse passing tests when Java source has not changed")
    args = parser.parse_args()
    frontend, backend = ROOT / "frontend", ROOT / "backend"
    if not args.frontend_already_built:
        if not (frontend / "node_modules").exists():
            subprocess.run(["npm", "ci"], cwd=frontend, check=True)
        subprocess.run(["npm", "run", "build"], cwd=frontend, check=True)
    source = frontend / "dist"
    if not (source / "index.html").exists():
        raise SystemExit("Build frontend/dist first.")
    destination = backend / "src/main/resources/static"
    marker = destination / ".paisa-generated"
    if destination.exists():
        if not marker.exists():
            raise SystemExit("Existing static resources are not marked as generated; review them before replacing.")
        shutil.rmtree(destination)
    shutil.copytree(source, destination)
    marker.write_text("Generated by scripts/build_release.py; rebuild from frontend sources.\n")
    command = ["mvn", "-B", "package"]
    if args.tests_already_passed:
        command.insert(1, "-DskipTests")
    subprocess.run(command, cwd=backend, check=True)
    print("Release ready: backend/target/paisa-1.0.0.jar")
    print("After backend restart, the complete frontend and API share http://127.0.0.1:8080/")
